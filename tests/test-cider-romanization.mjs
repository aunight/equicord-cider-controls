import { resolve as resolveFromCwd } from "node:path";
import { build } from "esbuild";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { mkdir } from "node:fs/promises";
import assert from "node:assert/strict";
await mkdir("./.cider-test-output", { recursive: true });
await build({ entryPoints:["src/userplugins/ciderControls.desktop/romanization.ts"], outfile:"./.cider-test-output/romanization.cjs", bundle:true, platform:"node", format:"cjs" });
const require = createRequire(resolveFromCwd("package.json"));
const analyzerRequire = createRequire(require.resolve("kuroshiro-analyzer-kuromoji"));
const dict = join(dirname(analyzerRequire.resolve("kuromoji/package.json")), "dict");
const { romanizeJapanese } = require("./.cider-test-output/romanization.cjs");
const line = text => ({ start:0, end:3, text, words:[] });
const sample = [line("僕は音楽を聴く"), { ...line("夢を見る"), romanization:"provided reading" }, line("Hello"), line("")];
const result = await romanizeJapanese(sample, "ja", dict);
assert.match(result[0].romanization, /^boku wa ongaku o kiku$/i);
assert.equal(result[1].romanization,"provided reading");
assert.equal(result[2].romanization,undefined);
assert.equal(result[3].romanization,undefined);
const chinese = [line("今天很好")];
assert.strictEqual(await romanizeJapanese(chinese,"zh",dict),chinese);
assert.equal((await romanizeJapanese(sample,"ja",dict))[0].romanization,result[0].romanization);
console.log("PASS: real local dictionary converts Japanese kanji, preserves supplied readings, skips Chinese/English/empty lines and reuses cached readings.");
